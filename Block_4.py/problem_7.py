"""
Sort a list of names alphabetically, then sort a list of numbers from largest to smallest
reverse = True"""
# Sorting alphabetically
name_list = ["Eddy","Mickle","John","Albert","Nikle"]
name_list.sort()
print(name_list)

# Reversing a list of numbers 
num_list = [11,3,8,22,13,9,17,23,15,10]
num_list.sort(reverse= True)
print(num_list)